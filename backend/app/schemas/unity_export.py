"""
BankFlow AI - Unity 2D Export Schemas (Phase 9)
Defines strict Pydantic v2 schemas for exporting simulation snapshots,
events, agent telemetry, and metrics to Unity.
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class RequestExportItem(BaseModel):
    """Visual request token metadata."""
    request_id: str
    service_type: str
    status: str
    stage: str
    priority: str = "MEDIUM"
    assigned_agent: Optional[str] = None
    assignment_version: int = 0
    retry_count: int = 0
    customer_id: Optional[int] = None
    account_id: Optional[int] = None
    created_at: Optional[str] = None
    updated_at: Optional[str] = None


class AgentExportItem(BaseModel):
    """Visual agent actor state and health telemetry."""
    agent_code: str
    agent_type: str
    availability_status: str
    processing_status: str
    health_status: str
    current_request_id: Optional[str] = None
    completed_count: int = 0
    failed_count: int = 0
    retry_count: int = 0
    is_paused: bool = False
    last_heartbeat_at: Optional[str] = None


class SimulationEventExportItem(BaseModel):
    """Chronological event exchanged between agents or lifecycle transition."""
    event_id: str
    tick: int = 0
    timestamp: str
    event_type: str
    request_id: str
    sender_agent: str
    receiver_agent: str
    previous_state: Optional[str] = None
    new_state: Optional[str] = None
    assignment_version: int = 0
    reason_code: Optional[str] = None
    payload: Optional[Dict[str, Any]] = None


class SimulationSnapshotExport(BaseModel):
    """Complete system snapshot at an individual simulation tick."""
    tick: int
    timestamp: str
    queue_counts: Dict[str, int]
    active_requests: List[RequestExportItem]
    agents: List[AgentExportItem]


class SimulationMetricsExport(BaseModel):
    """Authoritative benchmark performance metrics generated by Python/Mesa."""
    total_requests: int
    completed_requests: int
    failed_requests: int
    pending_requests: int
    human_review_requests: int
    recovered_requests: int
    avg_waiting_time_ticks: float
    avg_completion_time_ticks: float
    throughput_per_minute: float
    request_agent_utilization: float
    message_integrity_rate: float


class BranchExportItem(BaseModel):
    """Federated branch state metadata for Unity visualization (Phase 10)."""
    branch_id: str
    branch_name: str
    location: str
    status: str = "ACTIVE"
    active_agents: int = 0
    pending_requests: int = 0
    completed_requests: int = 0


class FederationEventExportItem(BaseModel):
    """Cross-branch federation event for Unity inter-branch trajectory replay (Phase 10)."""
    federation_event_id: str
    source_branch_id: str
    destination_branch_id: str
    request_id: Optional[str] = None
    event_type: str
    requested_scope: str
    authorization_result: str
    correlation_id: str
    event_status: str
    timestamp: str
    error_message: Optional[str] = None


class SimulationManifestExport(BaseModel):
    """Top-level simulation export manifest consumed by Unity 2D JSON Importer."""
    schema_version: str = "1.0.0"
    simulation_id: str
    scenario_name: str
    exported_at: str
    total_ticks: int
    total_events: int
    metrics: SimulationMetricsExport
    snapshots: List[SimulationSnapshotExport]
    events: List[SimulationEventExportItem]
    branches: List[BranchExportItem] = Field(default_factory=list)
    federation_events: List[FederationEventExportItem] = Field(default_factory=list)
